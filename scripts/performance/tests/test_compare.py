class Order(Verdicts):
    def resealed(self, plan, change):
        """A run whose shard 0 samples.jsonl lines pass through `change`, then resealed."""
        run = run_dir(self, plan, synthetic.constant(20))
        root = os.path.join(run, "shards/0")
        path = os.path.join(root, "samples.jsonl")
        with open(path, "rb") as stream:
            lines = stream.read().splitlines(True)
        with open(path, "wb") as stream:
            stream.write(b"".join(change(lines)))
        partial = len(change(list(lines))) != len(lines)
        synthetic.reseal_shard(root, (lambda doc: doc.update(
            status="interrupted", failure={"reason": "synthetic_interruption",
                                           "detail": "synthetic"})) if partial else None)
        return run

    def test_swapped_lines_with_freshly_rehashed_manifests_are_refused(self):
        def swap(lines):
            lines = list(lines)
            lines[20], lines[21] = lines[21], lines[20]
            return lines
        verdict = compare.compare(self.resealed(self.single(), swap))
        self.assert_result(verdict, "incomplete", ["reordered_records"])
        self.assertIn("samples.jsonl:22 holds sequence 20 after sequence 21",
                      verdict["aggregate"]["reasons"][0]["detail"])
        # The surviving records are reordered, not missing: every slot is still matched.
        self.assertEqual(verdict["aggregate"]["coverage"]["missing_records"], 0)
        self.assertEqual(self.case(verdict, FAST)["missing_records"], 0)
        self.assertEqual(self.case(verdict, FAST)["status"], "within_tolerance")

    def test_a_record_moved_far_out_of_place_is_refused(self):
        def move(lines):
            lines = list(lines)
            return [lines[-1]] + lines[:-1]
        verdict = compare.compare(self.resealed(self.single(), move))
        self.assert_result(verdict, "incomplete", ["reordered_records"])

    def test_a_repeated_sequence_is_refused(self):
        def repeat(lines):
            lines = list(lines)
            lines[31] = lines[30]
            return lines
        verdict = compare.compare(self.resealed(self.single(), repeat))
        codes = set(r["code"] for r in verdict["aggregate"]["reasons"])
        self.assertTrue({"duplicate_record", "reordered_records"} <= codes, codes)
        self.assertIn("samples.jsonl:32 holds sequence 30 after sequence 30",
                      " ".join(r["detail"] for r in verdict["aggregate"]["reasons"]))
        self.assert_result(verdict, "incomplete")

        def renumber(lines):
            lines = list(lines)
            record = json.loads(lines[31].decode("utf-8"))
            record["sequence"] = json.loads(lines[30].decode("utf-8"))["sequence"]
            lines[31] = contracts.canonical_bytes(record) + b"\n"
            return lines
        verdict = compare.compare(self.resealed(self.single(), renumber))
        codes = set(r["code"] for r in verdict["aggregate"]["reasons"])
        self.assertTrue({"identity_mismatch", "reordered_records"} <= codes, codes)
        self.assert_result(verdict, "incomplete")

    def test_monotone_partial_gaps_are_missing_not_reordered(self):
        def gaps(lines):
            # Warmup pair 2 and one measured record; sentinels stay complete.
            return [line for index, line in enumerate(lines) if index not in (12, 13, 30)]
        verdict = compare.compare(self.resealed(self.single(), gaps))
        codes = sorted(set(r["code"] for r in verdict["aggregate"]["reasons"]))
        self.assertEqual(codes, ["missing_records", "shard_not_complete"])
        self.assertEqual(verdict["aggregate"]["coverage"]["missing_records"], 3)
        self.assertEqual(self.case(verdict, FAST)["missing_records"], 3)
        self.assertEqual(verdict["shards"][0]["status"], "interrupted")


