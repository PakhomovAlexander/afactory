//! Optional local development for a captured command Worker. It uses the existing Sandbox,
//! CheckRuntime, container provider and af-process supervisor, never a second executor.
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;
use std::sync::atomic::AtomicBool;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use af_contracts::Command;
use af_contracts::task::development::*;
use af_contracts::task::execution::TaskInvocationV1;
use af_runner::task::WorkerReturn;
use af_sandbox::{CheckRuntime, ContainerProvider, Mode, Sandbox, WorkerContainerLayout};
use af_store::Cas;

use super::source::source_snapshot;
pub(crate) mod cache;

/// All private paths resolve inside the container. No Worker value can select a host path.
fn environment(
    request: &WorkerDevelopmentV3,
    binding: &WorkerDevelopmentBindingV3,
) -> Result<Vec<(String, String)>, String> {
    let directories: BTreeSet<_> = request
        .tools
        .keys()
        .map(|name| {
            Path::new(&binding.tools[name].program)
                .parent()
                .unwrap()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    let mut result = vec![
        (
            "PATH".into(),
            directories.into_iter().collect::<Vec<_>>().join(":"),
        ),
        ("HOME".into(), "/af/state/home".into()),
        ("TMPDIR".into(), "/af/scratch".into()),
        ("XDG_CONFIG_HOME".into(), "/af/state/config".into()),
        ("XDG_STATE_HOME".into(), "/af/state".into()),
        ("XDG_CACHE_HOME".into(), "/af/cache".into()),
    ];
    for (key, value) in &request.environment {
        let value = match symbolic_value(value)? {
            Some((root, relative)) => {
                let root = if root == "source" {
                    "/work".into()
                } else {
                    format!("/af/{root}")
                };
                if relative.is_empty() {
                    root
                } else {
                    format!("{root}/{relative}")
                }
            }
            None => value.clone(),
        };
        result.push((key.clone(), value));
    }
    Ok(result)
}

fn safe_mount(path: &Path) -> Result<(), String> {
    // Docker's --volume is a mini-language. Host paths are generated by AF, but a machine
    // temporary root can contain a delimiter. Refuse rather than reinterpret it as a mount.
    let path = path.to_str().ok_or("Development mount is not UTF-8")?;
    if path.contains([':', ',', '\n', '\r']) {
        return Err("Development mount contains a runtime delimiter".into());
    }
    Ok(())
}

fn checked_source(
    cas: &Cas,
    input: &TaskInvocationV1,
    writes_source: bool,
) -> Result<(String, af_source_git::Manifest), String> {
    let (id, _, mut manifest) = source_snapshot(
        cas,
        input
            .inputs
            .get("source")
            .ok_or("Development Worker requires source")?,
    )?;
    super::source::add_review_inputs(cas, input, writes_source, &id, &mut manifest)?;
    if manifest
        .entries
        .iter()
        .any(|entry| entry.kind == af_source_git::EntryKind::Symlink)
    {
        return Err("Worker development refuses symlinks in its source".into());
    }
    Ok((id, manifest))
}

#[allow(clippy::too_many_arguments)]
pub(super) fn invoke(
    cas: &Cas,
    input: &TaskInvocationV1,
    attempt_id: &str,
    context_id: &str,
    lineage: (&str, &str),
    request: &WorkerDevelopmentV3,
    command: &Command,
    files: &BTreeMap<String, Vec<u8>>,
    contract: &af_runner::task::WorkerContract,
    original: Sandbox,
    writes_source: bool,
    deadline_unix_ms: u64,
    cancellation: Option<&AtomicBool>,
) -> Result<(WorkerReturn, Option<Sandbox>), String> {
    let started = Instant::now();
    let remaining = deadline_unix_ms
        .checked_sub(unix_ms()?)
        .filter(|remaining| *remaining > 0)
        .ok_or("Worker development Attempt deadline expired before preparation")?;
    let deadline = started
        .checked_add(Duration::from_millis(remaining.min(request.limits.wall_ms)))
        .ok_or("Worker development deadline overflow")?;
    let binding = af_pipeline_config::task::development::resolve_binding(request)?;
    invoke_bound(
        cas,
        input,
        attempt_id,
        context_id,
        lineage,
        request,
        &binding,
        command,
        files,
        contract,
        original,
        writes_source,
        deadline,
        cancellation,
    )
}

#[allow(clippy::too_many_arguments)]
fn invoke_bound(
    cas: &Cas,
    input: &TaskInvocationV1,
    attempt_id: &str,
    context_id: &str,
    lineage: (&str, &str),
    request: &WorkerDevelopmentV3,
    binding: &WorkerDevelopmentBindingV3,
    command: &Command,
    files: &BTreeMap<String, Vec<u8>>,
    contract: &af_runner::task::WorkerContract,
    original: Sandbox,
    writes_source: bool,
    deadline: Instant,
    cancellation: Option<&AtomicBool>,
) -> Result<(WorkerReturn, Option<Sandbox>), String> {
    let started = Instant::now();
    let declared = started
        .checked_add(Duration::from_millis(request.limits.wall_ms))
        .ok_or("Worker development deadline overflow")?;
    let deadline = deadline.min(declared);
    let remaining = || {
        deadline
            .checked_duration_since(Instant::now())
            .filter(|duration| !duration.is_zero())
            .ok_or("Worker development deadline expired during preparation".to_owned())
    };
    remaining()?;
    binding.admit(request)?;
    let binding_value = serde_json::to_value(binding).map_err(|error| error.to_string())?;
    let binding_id = cas
        .put_json(&binding_value)
        .map_err(|error| error.to_string())?;
    if binding_id != request.binding_identity {
        return Err("Worker development binding identity changed".into());
    }
    let (source_snapshot_id, manifest) = checked_source(cas, input, writes_source)?;
    // A reviewer gets a second clone for experiments. The original still goes through the
    // source environment's unchanged-source checks; no experiment can become a candidate.
    let experiment = if writes_source {
        None
    } else {
        Some(
            Sandbox::materialize(&manifest, cas, Mode::EphemeralWrite)
                .map_err(|error| error.to_string())?,
        )
    };
    let source = experiment.as_ref().unwrap_or(&original);
    safe_mount(source.root())?;
    let input_manifest =
        af_source_git::scan_tree(source.root()).map_err(|error| error.to_string())?;
    let input_tree_digest = input_manifest.content_digest();
    if input_tree_digest != manifest.content_digest() {
        return Err(
            "Worker development source differs from the exact declared Snapshot and Review inputs"
                .into(),
        );
    }
    let input_manifest_id = cas
        .put_json(&serde_json::to_value(&input_manifest).map_err(|error| error.to_string())?)
        .map_err(|error| error.to_string())?;
    remaining()?;
    let selected = cache::selection(cas, input, request)?;
    let runtime = CheckRuntime::new().map_err(|error| error.to_string())?;
    let package = runtime.path().join("package");
    std::fs::create_dir(&package).map_err(|error| error.to_string())?;
    for (path, bytes) in files {
        let path = package.join(path);
        std::fs::create_dir_all(
            path.parent()
                .ok_or("Development package file has no parent")?,
        )
        .map_err(|error| error.to_string())?;
        std::fs::write(path, bytes).map_err(|error| error.to_string())?;
    }
    let mut roots = Vec::new();
    for root in [
        DevelopmentRootV1::State,
        DevelopmentRootV1::Scratch,
        DevelopmentRootV1::Build,
        DevelopmentRootV1::Cache,
        DevelopmentRootV1::Knowledge,
    ] {
        let path = runtime.path().join(format!("development-{}", root.name()));
        if !cache::restore(
            cas,
            selected.as_ref(),
            request,
            root,
            &path,
            Some(deadline),
            cancellation,
        )? {
            std::fs::create_dir(&path).map_err(|error| error.to_string())?;
        }
        if root == DevelopmentRootV1::State {
            for name in ["home", "config"] {
                std::fs::create_dir_all(path.join(name)).map_err(|error| error.to_string())?;
            }
        }
        safe_mount(&path)?;
        roots.push((
            path,
            root.name().into(),
            request.writable_roots.contains(&root),
        ));
    }
    safe_mount(&package)?;
    let base = original
        .readable_roots()
        .into_iter()
        .find(|root| root != original.root());
    if let Some(base) = &base {
        safe_mount(base)?;
    }
    let layout = WorkerContainerLayout {
        disk_bytes: request
            .limits
            .disk_bytes
            .ok_or("Missing aggregate disk bound")?,
        probe_shell: binding.probe_shell.clone(),
        package,
        roots,
        source_writable: request.writable_roots.contains(&DevelopmentRootV1::Source),
        base,
        processes: request
            .limits
            .processes
            .ok_or("Missing development process bound")?,
    };
    let cpu = request
        .limits
        .cpu_millicores
        .ok_or("Missing development CPU bound")?;
    let provider = ContainerProvider::with_runtime_before(
        &binding.runtime,
        deadline,
        &runtime.path().join("home"),
    )
    .with_image(&binding.image)
    .with_limits(
        request.limits.memory_bytes.map(|bytes| bytes.to_string()),
        Some(format!("{}.{:03}", cpu / 1000, cpu % 1000)),
    )
    .with_output_cap(request.limits.output_bytes as usize)
    .with_worker_layout(layout);
    remaining()?;
    provider.admit_worker_image(
        &runtime.path().join("home"),
        &binding.probe_shell,
        &std::iter::once(binding.checksum_program.clone())
            .chain(
                request
                    .tools
                    .keys()
                    .map(|name| binding.tools[name].program.clone()),
            )
            .collect::<Vec<_>>(),
        deadline,
        cancellation,
    )?;
    let environment = environment(request, binding)?;
    // Kernel-generated path variables are known non-secret image/private paths. Judge only
    // Worker literal values as possible credentials; a hash in a pinned tool path is data.
    for (key, value) in &request.environment {
        if af_telemetry::redact::secret_name(key)
            || symbolic_value(value)?.is_none()
                && af_telemetry::redact::looks_like_credential(value)
        {
            return Err("Worker development environment cannot carry credentials".into());
        }
    }
    let environment_id = cas
        .put_json(&serde_json::to_value(&environment).map_err(|error| error.to_string())?)
        .map_err(|error| error.to_string())?;
    let mut arguments = command.resolve().map_err(|error| error.to_string())?;
    for argument in &mut arguments {
        if let Some(path) = argument.strip_prefix("@package/") {
            if !files.contains_key(path) {
                return Err("Development harness names an uncaptured package file".into());
            }
            *argument = format!("/af/package/{path}");
        }
    }
    if arguments.len() > 1023
        || arguments
            .iter()
            .any(|value| value.len() > 4096 || af_telemetry::redact::looks_like_credential(value))
    {
        return Err(
            "Development command arguments are oversized or contain credential-shaped material"
                .into(),
        );
    }
    let (_, bytes) = contract.read_context(cas, context_id)?;
    let record_context = CommandRecordContext {
        cas,
        request,
        attempt_id,
        context_id,
        source_snapshot_id: &source_snapshot_id,
        input_tree_digest: &input_tree_digest,
        input_manifest_id: &input_manifest_id,
        environment_id: &environment_id,
        binding_id: &binding_id,
        experiment: experiment.is_some(),
    };
    // Identity preflight has no writable mounts and never executes project code. Its actual
    // bounded output and failures are retained too, even when no harness can be dispatched.
    let tools: Vec<_> = request
        .tools
        .keys()
        .map(|name| binding.tools[name].program.clone())
        .collect();
    let probe_root = runtime.path().join("identity-probe");
    std::fs::create_dir(&probe_root).map_err(|error| error.to_string())?;
    safe_mount(&probe_root)?;
    let probe_manifest = af_source_git::Manifest::new(vec![]).map_err(|error| error.to_string())?;
    let probe_digest = probe_manifest.content_digest();
    let probe_manifest_id = cas
        .put_json(&serde_json::to_value(&probe_manifest).map_err(|error| error.to_string())?)
        .map_err(|error| error.to_string())?;
    let probe_context = CommandRecordContext {
        input_tree_digest: &probe_digest,
        input_manifest_id: &probe_manifest_id,
        experiment: false,
        ..record_context
    };
    let probe_time = unix_ms()?;
    let probe_started = Instant::now();
    let probe = provider
        .clone()
        .with_identity_probe_root(&probe_root)
        .exec_worker_captured(
            &probe_root,
            &binding.checksum_program,
            &tools,
            &environment,
            Vec::new(),
            deadline,
            cancellation,
        )?;
    let probe_elapsed = probe_started.elapsed();
    let probe_text = std::str::from_utf8(&probe.capture.stdout).ok();
    let probe_lines: Vec<_> = probe_text
        .map(|text| text.lines().collect())
        .unwrap_or_default();
    let probe_framed = probe_lines.len() == request.tools.len()
        && request.tools.keys().zip(&probe_lines).all(|(name, line)| {
            let Some((hash, path)) = line.split_once("  ") else {
                return false;
            };
            hash.len() == 64
                && hash
                    .bytes()
                    .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
                && path == binding.tools[name].program
        });
    let probe_matches = probe_framed
        && request.tools.keys().zip(probe_lines).all(|(name, line)| {
            let tool = &binding.tools[name];
            line == format!(
                "{}  {}",
                tool.identity.trim_start_matches("sha256:"),
                tool.program
            )
        });
    let probe_clean = probe.cleanup_confirmed;
    let probe_success = probe_matches
        && probe
            .capture
            .status
            .as_ref()
            .is_ok_and(|status| status.success())
        && !probe.capture.stderr_held
        && !probe.capture.truncation.is_truncated();
    if !probe_success {
        let original = if probe_clean {
            Some(original)
        } else {
            preserve(runtime, experiment, original);
            None
        };
        let record = probe_context.record(
            WorkerCommandPurposeV1::ToolProbe,
            std::iter::once(binding.checksum_program.clone()).chain(tools).collect(),
            probe.capture, probe_time, probe_elapsed, probe_clean, None,
            probe_clean.then_some(&probe_manifest),
            Some("Worker development tool image is unavailable, its bounded probe failed, or an installed tool identity changed; dependencies are available-only".into()), probe_framed,
        )?;
        return Ok((record.worker_return(contract), original));
    }
    let probe_record = probe_context.record(
        WorkerCommandPurposeV1::ToolProbe,
        std::iter::once(binding.checksum_program.clone())
            .chain(tools)
            .collect(),
        probe.capture,
        probe_time,
        probe_elapsed,
        true,
        None,
        Some(&probe_manifest),
        None,
        true,
    )?;
    if probe_record.evidence.failure.is_some() {
        return Ok((probe_record.worker_return(contract), Some(original)));
    }
    let program = &binding.tools[&request.harness].program;
    let command_time = match unix_ms() {
        Ok(time) => time,
        Err(error) => return Ok((probe_record.rejected(error), Some(original))),
    };
    if let Err(error) = remaining() {
        return Ok((probe_record.rejected(error), Some(original)));
    }
    let command_started = Instant::now();
    let captured = provider.exec_worker_captured(
        source.root(),
        program,
        &arguments,
        &environment,
        bytes,
        deadline,
        cancellation,
    );
    let captured = match captured {
        Ok(captured) => captured,
        Err(error) => return Ok((probe_record.rejected(error), Some(original))),
    };
    let command_elapsed = command_started.elapsed();
    let cleanup_confirmed = captured.cleanup_confirmed;
    let final_manifest = if cleanup_confirmed && captured.filesystem_exported {
        bounded_final_manifest(source.root(), deadline, 16_384, 256 * 1024 * 1024)
    } else {
        None
    };
    let cache_runtime_path = runtime.path().to_path_buf();
    // Preserve before any fallible receipt write, even if receipt storage itself fails.
    let original = if cleanup_confirmed {
        Some(original)
    } else {
        preserve(runtime, experiment, original);
        None
    };
    let cache_records = cache::capture(
        cas,
        input,
        attempt_id,
        lineage,
        request,
        &cache_runtime_path,
        cleanup_confirmed,
        captured
            .capture
            .status
            .as_ref()
            .is_ok_and(|status| status.success())
            && !captured.capture.stderr_held
            && !captured.capture.truncation.is_truncated(),
        final_manifest
            .as_ref()
            .map(|manifest| (input_tree_digest.as_str(), manifest)),
        deadline,
        cancellation,
    )?;
    let mut record = record_context.record(
        WorkerCommandPurposeV1::Harness,
        std::iter::once(program.clone()).chain(arguments).collect(),
        captured.capture,
        command_time,
        command_elapsed,
        cleanup_confirmed,
        Some(&probe_record.evidence.stdout_id),
        final_manifest.as_ref(),
        None,
        false,
    )?;
    record.raw_artifact_ids.extend(cache_records);
    record
        .raw_artifact_ids
        .extend(probe_record.raw_artifact_ids);
    Ok((record.worker_return(contract), original))
}

/// Final experiment evidence is optional, but its host-side scan is never unbounded. The
/// workload has stopped before this pre-walk: no Worker can grow or replace entries between
/// the bounds check and the shared Manifest scanner. Oversized evidence is explicitly omitted.
fn bounded_final_manifest(
    root: &Path,
    deadline: Instant,
    max_entries: usize,
    max_bytes: u64,
) -> Option<af_source_git::Manifest> {
    let mut pending = vec![(root.to_owned(), 0usize)];
    let mut entries = 0usize;
    let mut bytes = 0u64;
    while let Some((directory, depth)) = pending.pop() {
        if depth > 64 || Instant::now() >= deadline {
            return None;
        }
        let metadata = std::fs::symlink_metadata(&directory).ok()?;
        if !metadata.is_dir() || metadata.file_type().is_symlink() {
            return None;
        }
        for entry in std::fs::read_dir(directory).ok()? {
            if Instant::now() >= deadline {
                return None;
            }
            let entry = entry.ok()?;
            entries = entries.checked_add(1)?;
            if entries > max_entries {
                return None;
            }
            let path = entry.path();
            if path.as_os_str().as_encoded_bytes().len() > 4096 {
                return None;
            }
            let metadata = std::fs::symlink_metadata(&path).ok()?;
            bytes = bytes.checked_add(metadata.len())?;
            if bytes > max_bytes {
                return None;
            }
            if metadata.is_dir() {
                pending.push((path, depth + 1));
            } else if !metadata.is_file() && !metadata.file_type().is_symlink() {
                return None;
            }
        }
    }
    af_source_git::scan_tree(root).ok()
}

fn unix_ms() -> Result<u64, String> {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|error| error.to_string())?
        .as_millis()
        .try_into()
        .map_err(|_| "Worker development clock overflow".into())
}

#[derive(Clone, Copy)]
struct CommandRecordContext<'a> {
    cas: &'a Cas,
    request: &'a WorkerDevelopmentV3,
    attempt_id: &'a str,
    context_id: &'a str,
    source_snapshot_id: &'a str,
    input_tree_digest: &'a str,
    input_manifest_id: &'a str,
    environment_id: &'a str,
    binding_id: &'a str,
    experiment: bool,
}
struct RecordedCommand {
    evidence: WorkerCommandEvidenceV1,
    stdout: Vec<u8>,
    raw_artifact_ids: Vec<String>,
}
impl RecordedCommand {
    fn rejected(self, error: String) -> WorkerReturn {
        WorkerReturn {
            notes: Default::default(),
            reply: Err(error),
            feedback_code: Some(af_contracts::task::feedback::TaskFeedbackCodeV1::ProcessFailure),
            usage: Some(af_contracts::task::usage::TaskTokenUsageV3::charge_only(0)),
            usage_observation: None,
            raw_artifact_ids: self
                .raw_artifact_ids
                .into_iter()
                .collect::<BTreeSet<_>>()
                .into_iter()
                .collect(),
            native_failure: None,
        }
    }
    fn worker_return(self, contract: &af_runner::task::WorkerContract) -> WorkerReturn {
        let process_failed = self.evidence.failure.is_some();
        let reply = match self.evidence.failure {
            Some(error) => Err(error),
            None => contract.validate_reply(&self.stdout),
        };
        let feedback_code = reply.as_ref().err().map(|_| {
            if process_failed {
                af_contracts::task::feedback::TaskFeedbackCodeV1::ProcessFailure
            } else {
                af_contracts::task::feedback::TaskFeedbackCodeV1::InvalidOutputContract
            }
        });
        let notes = af_runner::task::CallNotes {
            environment: self.evidence.purpose == WorkerCommandPurposeV1::ToolProbe,
            ..Default::default()
        };
        WorkerReturn {
            notes,
            reply,
            feedback_code,
            usage: Some(af_contracts::task::usage::TaskTokenUsageV3::charge_only(0)),
            usage_observation: None,
            raw_artifact_ids: self
                .raw_artifact_ids
                .into_iter()
                .collect::<BTreeSet<_>>()
                .into_iter()
                .collect(),
            native_failure: None,
        }
    }
}
impl CommandRecordContext<'_> {
    #[allow(clippy::too_many_arguments)]
    fn record(
        &self,
        purpose: WorkerCommandPurposeV1,
        command: Vec<String>,
        captured: af_process::SupervisedCapture,
        started_unix_ms: u64,
        elapsed: Duration,
        cleanup_confirmed: bool,
        tool_probe_output_id: Option<&str>,
        final_manifest: Option<&af_source_git::Manifest>,
        mut failure: Option<String>,
        verified_probe_output: bool,
    ) -> Result<RecordedCommand, String> {
        let exit_code = captured
            .status
            .as_ref()
            .ok()
            .and_then(|status| status.code());
        if let Err(error) = &captured.status {
            failure = Some(error.to_string());
        }
        if captured
            .status
            .as_ref()
            .is_ok_and(|status| !status.success())
        {
            failure = Some(format!("Development command exited {exit_code:?}"));
        }
        if captured.stderr_held {
            failure = Some("Development command stderr remained held after client exit".into());
        }
        if !cleanup_confirmed {
            failure = Some("Development command cleanup was not confirmed".into());
        }
        if let Some(reason) = captured.truncation.reason() {
            failure = Some(reason);
        }
        let stdout_total_bytes = captured
            .truncation
            .stdout
            .unwrap_or(captured.stdout.len() as u64);
        let stderr_total_bytes = captured
            .truncation
            .stderr
            .unwrap_or(captured.stderr.len() as u64);
        let mut redacted = false;
        let scrub = |bytes: Vec<u8>, redacted: &mut bool| {
            if af_telemetry::redact::looks_like_credential(&String::from_utf8_lossy(&bytes)) {
                *redacted = true;
                let marker = b"[omitted: output contains credential-shaped material]";
                marker[..(self.request.limits.output_bytes as usize).min(marker.len())].to_vec()
            } else {
                bytes
            }
        };
        // Verified checksum lines contain known digest literals. Arbitrary failed-probe text
        // is judged with the same credential filter as harness output.
        let stdout = if verified_probe_output {
            captured.stdout
        } else {
            scrub(captured.stdout, &mut redacted)
        };
        let stderr = scrub(captured.stderr, &mut redacted);
        if redacted {
            failure = Some("Development command output withheld for credential redaction".into());
        }
        let stdout_id = self.cas.put(&stdout).map_err(|error| error.to_string())?;
        let stderr_id = self.cas.put(&stderr).map_err(|error| error.to_string())?;
        let final_manifest_id = final_manifest
            .map(|manifest| {
                self.cas
                    .put_json(&serde_json::to_value(manifest).map_err(|error| error.to_string())?)
                    .map_err(|error| error.to_string())
            })
            .transpose()?;
        let mut omissions = BTreeSet::from([
            "internal_commands_unobserved".into(),
            "internal_model_output_unobserved".into(),
            "resources_are_runtime_client_only".into(),
        ]);
        if final_manifest.is_none() {
            omissions.insert("final_tree_unavailable".into());
        }
        let mut evidence = WorkerCommandEvidenceV1 {
            schema: COMMAND_EVIDENCE_SCHEMA.into(),
            purpose,
            attempt_id: self.attempt_id.into(),
            context_id: self.context_id.into(),
            source_snapshot_id: self.source_snapshot_id.into(),
            input_tree_digest: self.input_tree_digest.into(),
            input_manifest_id: self.input_manifest_id.into(),
            final_tree_digest: final_manifest.map(|manifest| manifest.content_digest()),
            final_manifest_id: final_manifest_id.clone(),
            experiment: self.experiment,
            command,
            cwd: "/work".into(),
            environment_id: self.environment_id.into(),
            binding_id: self.binding_id.into(),
            tool_probe_output_id: tool_probe_output_id.unwrap_or(&stdout_id).into(),
            started_unix_ms,
            elapsed_ms: elapsed.as_millis().try_into().unwrap_or(u64::MAX),
            exit_code,
            failure,
            resources: captured.rusage.map(|usage| CommandResourcesV1 {
                user_ms: usage.user_ms,
                system_ms: usage.system_ms,
                max_rss_bytes: usage.max_rss_bytes,
            }),
            stdout_id: stdout_id.clone(),
            stderr_id: stderr_id.clone(),
            returned_output_id: None,
            stdout_total_bytes,
            stderr_total_bytes,
            output_cap: self.request.limits.output_bytes,
            redacted,
            omissions,
        };
        if purpose == WorkerCommandPurposeV1::Harness && evidence.failure.is_none() {
            evidence.returned_output_id = Some(stdout_id.clone());
        }
        evidence.validate()?;
        let evidence_id = self
            .cas
            .put_json(&serde_json::to_value(&evidence).map_err(|error| error.to_string())?)
            .map_err(|error| error.to_string())?;
        let raw_artifact_ids = vec![
            evidence_id,
            stdout_id,
            stderr_id,
            self.binding_id.into(),
            self.environment_id.into(),
            self.input_manifest_id.into(),
        ]
        .into_iter()
        .chain(final_manifest_id)
        .collect();
        Ok(RecordedCommand {
            evidence,
            stdout,
            raw_artifact_ids,
        })
    }
}

fn preserve(runtime: CheckRuntime, experiment: Option<Sandbox>, original: Sandbox) {
    original.preserve();
    if let Some(experiment) = experiment {
        experiment.preserve();
    }
    runtime.preserve();
}

