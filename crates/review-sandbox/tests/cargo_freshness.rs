//! A native Cargo build must observe the current materialized Snapshot even when the target
//! contains newer artifacts from another Snapshot under the same warm key.

use std::fs::{FileTimes, OpenOptions};
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, SystemTime};

use review_sandbox::{Mode, Sandbox, TaskBuildCacheLock, lock_task_build_cache};
use review_source_git::{Entry, EntryKind, Manifest, fs_path};
use review_store::Cas;

fn snapshot(cas: &Cas, answer: &str) -> Manifest {
    let files = [
        (
            "Cargo.toml",
            "[package]\nname = \"freshness-app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n[dependencies]\nanswer = { path = \"answer\" }\n[workspace]\n",
        ),
        (
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"answer\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"freshness-app\"\nversion = \"0.1.0\"\ndependencies = [\n \"answer\",\n]\n",
        ),
        (
            "src/main.rs",
            "fn main() { print!(\"{}\", answer::value()); }\n",
        ),
        (
            "answer/Cargo.toml",
            "[package]\nname = \"answer\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        ),
        ("answer/src/lib.rs", answer),
    ];
    Manifest::new(
        files
            .into_iter()
            .map(|(path, source)| Entry {
                path: path.into(),
                kind: EntryKind::File,
                content: cas.put(source.as_bytes()).unwrap(),
                size: source.len() as u64,
            })
            .collect(),
    )
    .unwrap()
}

fn old_mtimes(root: &Path, manifest: &Manifest) {
    let old = SystemTime::UNIX_EPOCH + Duration::from_secs(1_600_000_000);
    for entry in &manifest.entries {
        let file = OpenOptions::new()
            .read(true)
            .open(root.join(fs_path(&entry.path)))
            .unwrap();
        file.set_times(FileTimes::new().set_modified(old)).unwrap();
    }
}

fn run_cargo(root: &Path, target: &Path, private: &Path) -> String {
    let rustup_home = std::env::var_os("RUSTUP_HOME").or_else(|| {
        std::env::var_os("HOME").map(|home| Path::new(&home).join(".rustup").into_os_string())
    });
    let mut command = Command::new("cargo");
    command
        .arg("run")
        .args(["--offline", "--locked", "--quiet"])
        .arg("--manifest-path")
        .arg(root.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(target)
        .env("HOME", private.join("home"))
        .env("CARGO_HOME", private.join("cargo"))
        .env("XDG_CACHE_HOME", private.join("xdg-cache"))
        .env("XDG_CONFIG_HOME", private.join("xdg-config"))
        .env("XDG_DATA_HOME", private.join("xdg-data"))
        .env("CARGO_INCREMENTAL", "0")
        .env_remove("RUSTFLAGS");
    if let Some(home) = rustup_home {
        command.env("RUSTUP_HOME", home);
    }
    let output = command.output().unwrap();
    assert!(
        output.status.success(),
        "cargo failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap()
}

#[test]
fn shared_cargo_target_builds_a_then_b_then_a_from_fixed_old_source_mtimes() {
    // Keep this tiny Cargo build in the checkout's own target, including under gate runs.
    let workspace = std::env::var_os("AF_WORKSPACE_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../.."));
    let target_root = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace.join("target"))
        .join("tmp");
    std::fs::create_dir_all(&target_root).unwrap();
    let temp = tempfile::tempdir_in(target_root).unwrap();
    let cas = Cas::open(temp.path().join("cas")).unwrap();
    let TaskBuildCacheLock::Held(warm) = lock_task_build_cache(
        &temp.path().join("warm"),
        &"a".repeat(64),
        &"b".repeat(64),
        "cargo_target",
        Duration::ZERO,
    )
    .unwrap() else {
        panic!("uncontended target lock");
    };
    warm.ensure().unwrap();
    let target = warm.path();
    let private = temp.path().join("private");
    let a = snapshot(&cas, "pub fn value() -> &'static str { \"A\" }\n");
    let b = snapshot(&cas, "pub fn value() -> &'static str { \"B\" }\n");

    let stored = a
        .entries
        .iter()
        .chain(&b.entries)
        .map(|entry| {
            let hex = entry.content.strip_prefix("sha256:").unwrap();
            let path = temp
                .path()
                .join("cas/objects")
                .join(&hex[..2])
                .join(&hex[2..]);
            let metadata = std::fs::metadata(&path).unwrap();
            (
                path,
                metadata.modified().unwrap(),
                metadata.permissions().mode(),
            )
        })
        .collect::<Vec<_>>();
    let first = Sandbox::materialize(&a, &cas, Mode::ReadOnly).unwrap();
    old_mtimes(first.root(), &a);
    assert_eq!(run_cargo(first.root(), target, &private), "A");

    let second = Sandbox::materialize(&b, &cas, Mode::ReadOnly).unwrap();
    old_mtimes(second.root(), &b);
    // The control demonstrates the stale-link failure with this same target and old blob.
    assert_eq!(run_cargo(second.root(), target, &private), "A");
    let source = second.root().join("answer/src/lib.rs");
    let mode_before = std::fs::metadata(&source).unwrap().permissions().mode();
    let bytes_before = std::fs::read(&source).unwrap();
    assert_eq!(
        second
            .refresh_source_mtimes(
                warm.latest_mtime(None, Duration::from_secs(5)).unwrap(),
                None,
                Duration::from_secs(5)
            )
            .unwrap(),
        b.entries.len()
    );
    assert_eq!(
        std::fs::metadata(&source).unwrap().permissions().mode(),
        mode_before
    );
    assert_eq!(std::fs::read(&source).unwrap(), bytes_before);
    assert_eq!(run_cargo(second.root(), target, &private), "B");

    let third = Sandbox::materialize(&a, &cas, Mode::ReadOnly).unwrap();
    old_mtimes(third.root(), &a);
    assert_eq!(
        third
            .refresh_source_mtimes(
                warm.latest_mtime(None, Duration::from_secs(5)).unwrap(),
                None,
                Duration::from_secs(5)
            )
            .unwrap(),
        a.entries.len()
    );
    assert_eq!(run_cargo(third.root(), target, &private), "A");
    for sandbox in [first, second, third] {
        assert!(sandbox.seal().unwrap().unchanged());
    }
    for entry in a.entries.iter().chain(&b.entries) {
        cas.verify(&entry.content).unwrap();
    }
    for (path, modified, mode) in stored {
        let metadata = std::fs::metadata(path).unwrap();
        assert_eq!(metadata.modified().unwrap(), modified, "CAS mtime changed");
        assert_eq!(metadata.permissions().mode(), mode, "CAS mode changed");
    }
}
